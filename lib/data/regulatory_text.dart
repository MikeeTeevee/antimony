/// Extract SEC number from legal reference string
/// Input: "SEC. 404 [15 U.S.C. 7262]..."
/// Output: "404"
String extractSecNumber(String? legalReference) {
  if (legalReference == null) return '';
  final match = RegExp(r'SEC\.\s*(\d+)').firstMatch(legalReference);
  return match?.group(1) ?? '';
}

/// Get the regulatory text for a given SEC section
/// Input: "SEC. 404 [15 U.S.C. 7262]..."
/// Output: Full SEC text from regulatoryTextMap
String getRegulatoryText(String? legalReference) {
  if (legalReference == null) return '';
  final secNumber = extractSecNumber(legalReference);
  if (secNumber.isEmpty) return '';

  final key = 'sec-$secNumber';
  return regulatoryTextMap[key] ??
      'Full regulatory text not available for this section.';
}
